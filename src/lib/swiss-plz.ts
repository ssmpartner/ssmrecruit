export function lookupPlz(plz: string): SwissLocation | undefined {
  return swissLocations.find(l => l.plz === plz);
}

export function searchPlz(query: string): SwissLocation[] {
  if (!query) return [];
  const q = query.toLowerCase();
  return swissLocations.filter(l =>
    l.plz.startsWith(q) || l.city.toLowerCase().includes(q)
  ).slice(0, 10);
}

export const cantons = [...new Set(swissLocations.map(l => l.cantonCode))].sort().map(code => {
  const loc = swissLocations.find(l => l.cantonCode === code)!;
  return { code, name: loc.canton };
});
